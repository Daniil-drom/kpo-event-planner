CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email VARCHAR(320) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT users_email_normalized CHECK (email = lower(btrim(email)) AND email <> '')
);

CREATE TABLE cities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kudago_slug VARCHAR(32) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    timezone VARCHAR(64) NOT NULL
);

CREATE TABLE places (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kudago_id BIGINT NOT NULL UNIQUE,
    city_id BIGINT NOT NULL REFERENCES cities(id),
    title TEXT NOT NULL,
    address TEXT,
    latitude NUMERIC(9, 6),
    longitude NUMERIC(9, 6),
    site_url TEXT,
    CHECK (latitude BETWEEN -90 AND 90),
    CHECK (longitude BETWEEN -180 AND 180)
);

CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kudago_id BIGINT NOT NULL UNIQUE,
    city_id BIGINT NOT NULL REFERENCES cities(id),
    place_id BIGINT REFERENCES places(id),
    title TEXT NOT NULL,
    description TEXT,
    price TEXT,
    is_free BOOLEAN NOT NULL DEFAULT FALSE,
    age_restriction VARCHAR(32),
    site_url TEXT NOT NULL,
    poster_url TEXT,
    publication_date TIMESTAMPTZ,
    fetched_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE event_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    start_at TIMESTAMPTZ,
    end_at TIMESTAMPTZ,
    is_continuous BOOLEAN NOT NULL DEFAULT FALSE,
    is_endless BOOLEAN NOT NULL DEFAULT FALSE,
    CHECK (end_at IS NULL OR start_at IS NULL OR end_at >= start_at)
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL
);

CREATE TABLE event_categories (
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES categories(id),
    PRIMARY KEY (event_id, category_id)
);

CREATE TABLE user_visits (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE RESTRICT,
    status VARCHAR(32) NOT NULL,
    start_at TIMESTAMPTZ,
    end_at TIMESTAMPTZ,
    conflict_accepted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT visits_status CHECK (status IN ('WANT_TO_VISIT', 'PLANNED', 'VISITED')),
    CONSTRAINT visits_interval CHECK (
        (start_at IS NULL AND end_at IS NULL) OR
        (start_at IS NOT NULL AND end_at IS NOT NULL AND end_at > start_at)
    ),
    CONSTRAINT planned_visit_has_time CHECK (
        status <> 'PLANNED' OR (start_at IS NOT NULL AND end_at IS NOT NULL)
    )
);
-- Пересечения проверит сервис: пользователь имеет право подтвердить конфликт.
-- updated_at обновляет сервис при изменении записи.

CREATE TABLE sync_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id BIGINT NOT NULL REFERENCES cities(id),
    status VARCHAR(32) NOT NULL CHECK (status IN ('RUNNING', 'SUCCESS', 'FAILED')),
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ,
    error_message TEXT,
    CHECK (finished_at IS NULL OR finished_at >= started_at)
);

CREATE INDEX events_city_free_publication_idx ON events (city_id, is_free, publication_date DESC);
CREATE INDEX event_sessions_period_idx ON event_sessions (start_at, end_at, event_id);
CREATE INDEX event_sessions_event_idx ON event_sessions (event_id);
CREATE INDEX event_categories_category_idx ON event_categories (category_id, event_id);
CREATE INDEX user_visits_status_time_idx ON user_visits (user_id, status, start_at);
CREATE INDEX user_visits_interval_idx ON user_visits (user_id, start_at, end_at);
CREATE INDEX user_visits_event_idx ON user_visits (event_id);
CREATE INDEX sync_runs_city_time_idx ON sync_runs (city_id, started_at DESC);
